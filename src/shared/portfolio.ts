/** Published owner records take precedence; never overwrite or duplicate their slug. */
export function mergeEditorial(
  records: ContentRecord[],
  originals: ContentRecord[],
) {
  const slugs = new Set(records.map((record) => record.slug));
  return [...records, ...originals.filter((record) => !slugs.has(record.slug))];
}
